inline const char *tlsRootForUrl(const char *url) {
  const char *digicert[]={"https://matchweb.sports.qq.com/","https://esports-data.5eplaycdn.com/"};
  for(const char *prefix:digicert)if(!std::strncmp(url,prefix,std::strlen(prefix)))return kDigiCertG2;
  const char *cloud="https://jks0502.xyz/";
  return !std::strncmp(url,cloud,std::strlen(cloud))?kCloudflareRoots:nullptr;
}
inline void configureTlsTrust(CooperativeSecureClient &client,const char *url) {
  if(const char *root=tlsRootForUrl(url))client.setCACert(root);
  else client.setCACertBundle(kCampusCaBundle,sizeof(kCampusCaBundle));
}
