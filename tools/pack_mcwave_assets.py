"""Pack mcwave's largest read-only assets so two OTA app slots fit in 4MB.

Inputs (unchanged sources): WeatherClock/SportsFonts.h, WeatherClock/NailongSprite.h.
Output: WeatherClock/PackedAssetsData.h

- Sports glyph index: per glyph only (code, width) in 3 bytes; the bitmap offset
  is a checkpoint every 32 glyphs plus ceil(width/8)*size per glyph, with an
  explicit exception list where the original generator reused/reordered bits.
- Sports glyph bitmaps: raw-DEFLATE blocks of at most 4096 bytes that never
  split a glyph; a CRC32 per block is checked after inflating on the device.
- Nailong frames: each 1456-byte frame is its own raw-DEFLATE stream.
The device inflates with the ESP32 ROM (tinfl). Host builds (no ESP32 macro)
get the original raw bytes instead, so host tests exercise the same index and
block arithmetic. Every glyph and frame is verified to round-trip here.
"""
import re, sys, zlib, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent / 'WeatherClock'
BLOCK = 4096
CHECKPOINT = 32

def c_bytes(text):
    return bytes(int(v, 0) for v in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b', text))

def deflate(data):
    c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    out = c.compress(data) + c.flush()
    assert zlib.decompress(out, -15) == data
    return out

sports = (ROOT / 'SportsFonts.h').read_text(encoding='utf-8')
bits_src = sports[sports.index('kSportsFontBits[]={') + len('kSportsFontBits[]={'):]
bits = c_bytes(bits_src[:bits_src.index('};')])
glyph_src = sports[sports.index('kSportsGlyphs[]={'):]
glyphs = [tuple(int(x) for x in m) for m in re.findall(r'\{(\d+),(\d+),(\d+),(\d+)\}', glyph_src[:glyph_src.index('};')])]
assert all(g[0] <= 0xFFFF and g[2] <= 255 for g in glyphs)
assert all((glyphs[i][1], glyphs[i][0]) < (glyphs[i + 1][1], glyphs[i + 1][0]) for i in range(len(glyphs) - 1)), 'index must stay sorted'
nail = (ROOT / 'NailongSprite.h').read_text(encoding='utf-8')
count = int(re.search(r'kNailongPoseCount=(\d+)', nail).group(1))
frame = int(re.search(r'kNailongBits\[kNailongPoseCount\]\[(\d+)\]', nail).group(1))
nail_bits = c_bytes(nail[nail.index('[%d]={' % frame) + len('[%d]={' % frame):].split('};')[0])
assert len(nail_bits) == count * frame

span = lambda g: ((g[2] + 7) // 8) * g[1]
sizes = sorted({g[1] for g in glyphs})
size_first = [next(i for i, g in enumerate(glyphs) if g[1] == s) for s in sizes]

# Offsets: checkpoint every CHECKPOINT glyphs, cumulative spans in between,
# explicit exceptions where the original offset differs.
checkpoints = [glyphs[i][3] for i in range(0, len(glyphs), CHECKPOINT)]
exceptions = []
for i, g in enumerate(glyphs):
    expected = g[3] if i % CHECKPOINT == 0 else computed + span(glyphs[i - 1])
    if expected != g[3]:
        exceptions.append((i, g[3]))
    computed = g[3]
# The device model (PackedAssets.cpp sportsOffset) must reproduce every offset:
# start at the group checkpoint, then each glyph begins at its exception offset
# if it has one, otherwise right after the previous glyph.
exception_set = dict(exceptions)
for i, g in enumerate(glyphs):
    base = (i // CHECKPOINT) * CHECKPOINT; off = checkpoints[i // CHECKPOINT]
    for k in range(base, i + 1):
        if k > base: off += span(glyphs[k - 1])
        off = exception_set.get(k, off)
    assert off == g[3], f'offset model failed at glyph {i}'

# Blocks that never split a glyph's bitmap.
spans = sorted({(g[3], g[3] + span(g)) for g in glyphs})
blocks = []; start = 0; end = 0
for a, b in spans:
    if b - start > BLOCK and end > start:
        blocks.append((start, end)); start = a
    end = max(end, b)
blocks.append((start, len(bits)))
for g in glyphs:
    a, b = g[3], g[3] + span(g)
    assert any(s <= a and b <= e for s, e in blocks), f'glyph splits a block: {g}'
packed_blocks = [deflate(bits[s:e]) for s, e in blocks]
packed_frames = [deflate(nail_bits[i * frame:(i + 1) * frame]) for i in range(count)]

def arr(name, ctype, values, per=24):
    vals = list(values)
    lines = [','.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f'static const {ctype} {name}[{len(vals)}]={{\n' + ',\n'.join(lines) + '\n};\n'

def blob(name, chunks):
    data = b''.join(chunks); offsets = [0]
    for c in chunks: offsets.append(offsets[-1] + len(c))
    return arr(name, 'uint8_t', data, 40), offsets

font_blob, font_offsets = blob('kSportsPackedBits', packed_blocks)
nail_blob, nail_offsets = blob('kNailongPacked', packed_frames)
crc = [zlib.crc32(bits[s:e]) for s, e in blocks]
out = ['// Generated by tools/pack_mcwave_assets.py from SportsFonts.h and NailongSprite.h. Do not edit.',
       '#pragma once', '#include <stdint.h>',
       f'constexpr uint16_t kSportsGlyphCount={len(glyphs)};',
       f'constexpr uint8_t kSportsCheckpointEvery={CHECKPOINT};',
       f'constexpr uint16_t kSportsBlockCount={len(blocks)},kSportsBlockMax={BLOCK};',
       f'constexpr uint8_t kNailongFrames={count};constexpr uint16_t kNailongFrameBytes={frame};',
       arr('kSportsSizes', 'uint8_t', sizes),
       arr('kSportsSizeFirst', 'uint16_t', size_first + [len(glyphs)]),
       arr('kSportsCodes', 'uint16_t', (g[0] for g in glyphs)),
       arr('kSportsWidths', 'uint8_t', (g[2] for g in glyphs)),
       arr('kSportsCheckpoints', 'uint32_t', checkpoints),
       f'constexpr uint16_t kSportsExceptionCount={len(exceptions)};',
       arr('kSportsExceptionIndex', 'uint16_t', (i for i, _ in exceptions)),
       arr('kSportsExceptionOffset', 'uint32_t', (o for _, o in exceptions)),
       arr('kSportsBlockStart', 'uint32_t', [s for s, _ in blocks] + [len(bits)]),
       arr('kSportsBlockCrc', 'uint32_t', crc),
       '#if defined(ESP32)',
       arr('kSportsPackedOffset', 'uint32_t', font_offsets),
       font_blob,
       arr('kNailongPackedOffset', 'uint32_t', nail_offsets),
       nail_blob,
       '#else',
       '// Host tests: the original bytes, addressed through the same index and blocks.',
       arr('kSportsRawBits', 'uint8_t', bits, 40),
       arr('kNailongRaw', 'uint8_t', nail_bits, 40),
       '#endif', '']
(ROOT / 'PackedAssetsData.h').write_text('\n'.join(out), encoding='utf-8')
index = len(glyphs) * 3 + len(checkpoints) * 4 + len(exceptions) * 6 + len(sizes) * 3 + len(blocks) * 12
print(f'glyphs={len(glyphs)} exceptions={len(exceptions)} blocks={len(blocks)}')
print(f'index {len(glyphs) * 12} -> {index}; font bits {len(bits)} -> {font_offsets[-1]}; nailong {len(nail_bits)} -> {nail_offsets[-1]}')
print(f'saved {len(glyphs) * 12 + len(bits) + len(nail_bits) - index - font_offsets[-1] - nail_offsets[-1]} bytes')
