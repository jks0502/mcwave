"""Create only the glyphs used by this fixed clock/weather interface."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import json

ROOT = Path(__file__).resolve().parents[1]
SKETCH = ROOT / "WeatherClock"
FONTS = ROOT / "design" / "fonts"

def main():
    source = (SKETCH / "Display.h").read_text(encoding="utf-8")
    source += (SKETCH / "WeatherData.h").read_text(encoding="utf-8")
    source += (SKETCH / "RainForecast.h").read_text(encoding="utf-8")
    source += (SKETCH / "CampusPortal.h").read_text(encoding="utf-8")
    quotes = "".join(json.loads((ROOT / "design" / "quotes-100.json").read_text(encoding="utf-8")))
    chars = sorted(set(chr(i) for i in range(32, 127)) |
                   {c for c in source if ord(c) >= 0x3000} | {"°", "·"})
    # Sayings are rendered only at 13px; other sizes need only interface text.
    quote_chars = sorted(set(chars) | set(quotes))
    glyphs, bits = [], bytearray()
    specs = [(11, chars, "NotoSansSC", [400]), (12, chars, "NotoSansSC", [500]),
             (13, quote_chars, "NotoSansSC", [500]), (14, chars, "NotoSansSC", [500]),
             (17, chars, "NotoSansSC", [700]), (26, list("0123456789.-°C%"), "Nunito", [800]),
             (32, list("0123456789.-°C%"), "Nunito", [800]),
             (72, list("0123456789:-"), "Fredoka", [500, 100])]
    for size, subset, family, axes in specs:
        font = ImageFont.truetype(str(FONTS / (family + ".ttf")), size)
        font.set_variation_by_axes(axes)
        for c in subset:
            width = max(1, round(font.getlength(c)))
            image = Image.new("L", (width, size), 0)
            draw = ImageDraw.Draw(image)
            box = draw.textbbox((0, 0), c, font=font)
            draw.text(((width - (box[2]-box[0]))//2 - box[0],
                       (size - (box[3]-box[1]))//2 - box[1]), c, font=font, fill=255)
            glyphs.append((ord(c), size, width, len(bits)))
            bits.extend(image.point(lambda p: 255 if p >= 100 else 0, "1").tobytes())
    glyphs.sort(key=lambda g: (g[1], g[0]))
    assert len({(g[1], g[0]) for g in glyphs}) == len(glyphs)
    header = "// Generated by tools/prepare_fonts.py; OFL Noto Sans SC, Nunito and Fredoka.\n"
    header += "#pragma once\n#include <stdint.h>\n"
    header += "struct Glyph { uint32_t code; uint8_t size, width; uint32_t offset; };\n"
    header += "static const uint8_t kFontBits[] = {\n"
    header += "\n".join("  " + ",".join(f"0x{x:02x}" for x in bits[i:i+24]) + ","
                        for i in range(0, len(bits), 24))
    header += "\n};\nstatic const Glyph kGlyphs[] = {\n"
    header += "\n".join(f"  {{{cp},{sz},{w},{off}}}," for cp, sz, w, off in glyphs)
    header += "\n};\n"
    (SKETCH / "Fonts.h").write_text(header, encoding="utf-8")
    print(f"Generated {len(glyphs)} glyphs, {len(bits)} bitmap bytes.")

if __name__ == "__main__":
    main()
